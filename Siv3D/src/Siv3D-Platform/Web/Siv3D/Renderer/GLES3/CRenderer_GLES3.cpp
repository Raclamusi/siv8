	////////////////////////////////////////////////////////////////
	//
	//	init
	//
	////////////////////////////////////////////////////////////////

	void CRenderer_GLES3::init()
	{
		LOG_SCOPED_DEBUG("CRenderer_GLES3::init()");

		m_pTexture		= static_cast<CTexture_GLES3*>(SIV3D_ENGINE(Texture));
		m_pRenderer2D	= static_cast<CRenderer2D_GLES3*>(SIV3D_ENGINE(Renderer2D));

		m_window = static_cast<GLFWwindow*>(SIV3D_ENGINE(Window)->getHandle());

		::glfwMakeContextCurrent(m_window);
		::glfwSwapInterval(1);
		if (::glewInit() != GLEW_OK)
		{
			throw InternalEngineError{ U"glewInit() failed" };
		}

		m_backBuffer.init(this);
		m_blendState.init();
		m_rasterizerState.init();
		m_samplerState.init();
		m_depthStencilState.init();

		m_pTexture->init();
	}

	////////////////////////////////////////////////////////////////
	//
	//	waitForFrame
	//
	////////////////////////////////////////////////////////////////

	void CRenderer_GLES3::waitForFrame() {} // do nothing

	////////////////////////////////////////////////////////////////
	//
	//	beginFrame
	//
	////////////////////////////////////////////////////////////////

	void CRenderer_GLES3::beginFrame()
	{
		m_backBuffer.clear(GLES3ClearTarget::Scene | GLES3ClearTarget::BackBuffer);

		if (const Size windowFrameBufferSize = SIV3D_ENGINE(Window)->getState().frameBufferSize;
			windowFrameBufferSize != m_backBuffer.getBackBufferSize())
		{
			m_backBuffer.resizeBackBuffer(windowFrameBufferSize);
		}
	}

	////////////////////////////////////////////////////////////////
	//
	//	flush
	//
	////////////////////////////////////////////////////////////////

	void CRenderer_GLES3::flush()
	{
		m_pRenderer2D->flush();

		m_backBuffer.renderSceneToBackBuffer();
	}

	////////////////////////////////////////////////////////////////
	//
	//	present
	//
	////////////////////////////////////////////////////////////////

	bool CRenderer_GLES3::present()
	{
		::glfwSwapBuffers(m_window);

		return true;
	}

